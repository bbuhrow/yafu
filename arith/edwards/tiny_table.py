#!/usr/bin/env python3
"""
Emit edw_tiny_curves.h: GKL family (iv) curves (a = -1, d = -e^4) with a
non-torsion point whose projective constants fit in 63 bits, for
microecm_edw / tinyecm_edw to use as their first curves (a few
multiplications to load, against ~46 for the general construction).

Sources: curves_iv.json (tiny_curves.py search) and GKL's [m]Q for small
m.  Curves d and 1/d are isomorphic for d = -e^4 (same group order), so
only one of each pair is kept; GKL m = 1 is curve "4" of the search.

usage: tiny_table.py OUT.h
"""
import json
import os
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
LIM = 1 << 63


def gkl_point(m):
    """[m]Q on E': y^2 = x^3 - x^2 - 9x + 9, Q = (5, 8), affine rationals"""
    def add(P, Q):
        if P is None:
            return Q
        (x1, y1), (x2, y2) = P, Q
        if x1 == x2:
            if y1 + y2 == 0:
                return None
            l = (3 * x1 * x1 - 2 * x1 - 9) / (2 * y1)
        else:
            l = (y2 - y1) / (x2 - x1)
        x3 = l * l + 1 - x1 - x2
        return (x3, l * (x1 - x3) - y1)
    R = None
    for _ in range(m):
        R = add(R, (F(5), F(8)))
    return R


def gkl_curve(m):
    x, y = gkl_point(m)
    t = (4 * x + 4) / (y - 4)
    e = (t * t + 4 * t) / (t * t - 4)
    x1 = (2 * t ** 3 + 2 * t * t - 8 * t - 8) / (t ** 4 + 6 * t ** 3 + 12 * t * t + 16 * t)
    y1 = ((t ** 6 + 6 * t ** 5 + 10 * t ** 4 - 16 * t ** 3 - 48 * t * t - 32 * t - 32)
          / (t ** 6 + 6 * t ** 5 + 10 * t ** 4 + 16 * t ** 3 + 48 * t * t + 64 * t))
    return -e ** 4, x1, y1


def constants(d, x, y):
    assert -x * x + y * y == 1 + d * x * x * y * y
    X = x.numerator * y.denominator
    Y = y.numerator * x.denominator
    Z = x.denominator * y.denominator
    T = x.numerator * y.numerator
    return [X, Y, Z, T, d.numerator, d.denominator]


def main():
    out = sys.argv[1]
    cands = []
    for c in json.load(open(os.path.join(HERE, 'curves_iv.json'))):
        cands.append(('search g = %s' % c['param'], F(c['dn'], c['dd']), F(c['x']), F(c['y'])))
    for m in (2, 3):
        d, x1, y1 = gkl_curve(m)
        cands.append(('GKL m = %d' % m, d, x1, y1))
    keep, seen = [], set()
    for name, d, x, y in cands:
        key = min(abs(d), 1 / abs(d))
        k = constants(d, x, y)
        if key in seen or max(abs(v) for v in k) >= LIM:
            continue
        seen.add(key)
        keep.append((name, k))
    L = ['/* generated by arith/edwards/tiny_table.py: GKL family (iv) curves',
         '   -x^2 + y^2 = 1 + d x^2 y^2, d = dn/dd = -e^4, with a non-torsion point',
         '   (X : Y : Z : T) = (xn yd : yn xd : xd yd : xn yn), x = xn/xd, y = yn/yd,',
         '   whose constants fit in 63 bits.  One curve per isomorphism class',
         '   (d ~ 1/d).  Used as the first',
         '   curves of microecm_edw before the general GKL construction. */',
         '#ifndef EDW_TINY_CURVES_H',
         '#define EDW_TINY_CURVES_H',
         '#include <stdint.h>',
         '#define EDW_TINY_NCURVES %d' % len(keep),
         '/* X, Y, Z, T, dn, dd */',
         'static const int64_t edw_tiny_curves[EDW_TINY_NCURVES][6] = {']
    for name, k in keep:
        L.append('    { %s },   /* %s */' % (', '.join('%dLL' % v for v in k), name))
    L += ['};', '#endif']
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print('%d curves -> %s' % (len(keep), out))
    for name, k in keep:
        print('  %-18s max %d bits' % (name, max(abs(v) for v in k).bit_length()))


if __name__ == '__main__':
    main()

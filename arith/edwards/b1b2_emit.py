#!/usr/bin/env python3
"""
Emit factor/gmp-ecm/edw_tiny_v2.h: the re-tuned microecm_edw levels of the
B1 / B2 study (b1b2_study.py, plan doc Part I).  Per level: the stage-1
chain for s(B1, policy) and the stage-2 table for B2 = mult B1 in the
generic format of uedw_stage2_gen: giant windows A = 30, 150, 270, ...
(step 120); entry 0 = advance to the next window, else a baby b (cross
term at A +- b).

  b1b2_emit.py [out.h]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tiny_chains as tc        # noqa: E402
import s2_tables as s2          # noqa: E402
import b1b2_study as st         # noqa: E402

# (B1, scalar policy (k2, kodd), B2 multiplier): from b1b2_study.py plan 16 32 two
# (balanced inputs, calibrated cost model; b1b2_plan_two.txt)
LEVELS2 = [
    (20, (8, 2), 25),
    (27, (16, 4), 25),
    (47, (8, 2), 25),
    (70, (8, 2), 20),
    (85, (16, 4), 20),
    (125, (8, 2), 25),
    (165, (8, 2), 20),
    (205, (16, 4), 20),
]


def gen_table(B1, B2):
    """generic-format entries from A = 30"""
    tab = s2.table(B1, B2)
    out = []
    A = 30
    for At, bs in tab:
        while A < At:
            out.append(0)
            A += 120
        out.extend(bs)
    return out


def main():
    fname = sys.argv[1] if len(sys.argv) > 1 else os.path.join(tc.SRC, 'edw_tiny_v2.h')
    L = ['/* generated by arith/edwards/b1b2_emit.py: the re-tuned microecm_edw',
         '   levels of the B1 / B2 study (arith/micro_tiny_edwards_plan.md, Part I).',
         '   Per level: s = prod over primes q <= B1 of q^e, q^e <= k B1 (k = k2 for',
         '   q = 2, kodd for odd q); its Edwards chain (as edw_tiny_chains.h); and',
         '   the stage-2 table for B2 = mult B1: giant windows A = 30 + 120 j, entry',
         '   0 = next window, else a baby b (cross term at A +- b). */',
         '#ifndef EDW_TINY_V2_H', '#define EDW_TINY_V2_H', '#include <stdint.h>']
    rows = []
    for B1, pol, mult in LEVELS2:
        s = st.scalar(B1, pol)
        r = tc.edw_level(s, 1.0, mmax=15)[0]
        total, m, nd, na, tcost, ops, tz = r
        top = tc.top_of(s, ops, tz)
        assert tc.chain_eval(ops, top) << tz == s
        enc = [0 if o == 'D' else o for o in ops]
        L.append('/* B1 %d: s policy (%d, %d), %d bits; B2 = %d B1 */'
                 % (B1, pol[0], pol[1], s.bit_length(), mult))
        L.append('static const int8_t edw2_chain_%d[%d] = {' % (B1, len(enc)))
        for i in range(0, len(enc), 24):
            L.append('    ' + ','.join(str(v) for v in enc[i:i + 24]) + ',')
        L.append('};')
        tb = gen_table(B1, mult * B1)
        L.append('static const uint8_t edw2_s2_%d[%d] = {' % (B1, len(tb)))
        for i in range(0, len(tb), 24):
            L.append('    ' + ','.join(str(v) for v in tb[i:i + 24]) + ',')
        L.append('};')
        rows.append('    { %d, %d, edw2_chain_%d, %d, %d, %d, %d, edw2_s2_%d, %d },'
                    % (B1, mult * B1, B1, len(enc), m, top, tz, B1, len(tb)))
    L.append('typedef struct {')
    L.append('    uint32_t B1, B2;')
    L.append('    const int8_t *ch;')
    L.append('    int len, m, top, tz;')
    L.append('    const uint8_t *s2;')
    L.append('    int s2len;')
    L.append('} edw2_level_t;')
    L.append('#define EDW2_NLEVELS %d' % len(rows))
    L.append('static const edw2_level_t edw2_levels[EDW2_NLEVELS] = {')
    L.extend(rows)
    L.append('};')
    L.append('#endif')
    open(fname, 'w', newline='\n').write('\n'.join(L) + '\n')
    print('wrote', fname)


if __name__ == '__main__':
    main()
